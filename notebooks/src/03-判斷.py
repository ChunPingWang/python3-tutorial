# ### 三個新手必踩的點
#
# **1️⃣ 冒號不能忘** —— 忘了會得到 `SyntaxError: expected ':'`
#
# **2️⃣ 縮排就是範圍** —— 其他語言用 `{ }`，Python 用縮排。一層 4 個空格，不要用 Tab、不要混用。
