# ✔ 正確：elif 命中一個就不再往下
if 分數 >= 90:
    等級 = "A"
elif 分數 >= 80:
    等級 = "B"
elif 分數 >= 70:
    等級 = "C"
else:
    等級 = "D"
print("用 elif：", 等級)

# %%
# ✖ 錯誤：全部用 if，每個都會檢查，後面的會覆蓋前面的
分數 = 95
if 分數 >= 90:
    等級 = "A"
if 分數 >= 80:
    等級 = "B"      # 95 分的人在這裡被改成 B
if 分數 >= 70:
    等級 = "C"      # ...然後又被改成 C
print("全用 if：", 等級, "← 95 分變成 C，錯了！")

# %% [markdown]
# ⚠️ **順序也很重要。** 把 `>= 70` 寫在最前面，85 分會變成 C。
# **寫多層 `elif` 要從最嚴格的條件開始。**

