# %%
# match（Python 3.10+）：多個「等於某個值」的分支，比一長串 elif 清楚
def 杯型加價(杯型):
    match 杯型:
        case "大杯":
            return 10
        case "中杯":
            return 0
        case "小杯":
            return -5
        case _:                      # _ 代表「其他」
            raise ValueError(f"未知杯型：{杯型}")


print([杯型加價(x) for x in ["大杯", "中杯", "小杯"]])
assert 杯型加價("大杯") == 10
print("🟢 match 正常（需要 Python 3.10 以上）")

