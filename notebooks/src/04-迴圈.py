# ## 4.4 range()：產生一串數字

# %%
print(list(range(5)))          # 0~4  ⚠️ 不含 5
print(list(range(1, 6)))       # 起點, 終點（不含）
print(list(range(0, 10, 2)))   # 起點, 終點, 間隔
print(list(range(5, 0, -1)))   # 倒數

# %% [markdown]
# ⚠️ **`range(5)` 不包含 5**（半開區間）。
# 好處是 `range(len(清單))` 剛好對應所有合法索引，而且 `range(a, b)` 的長度剛好是 `b - a`。

# %%
# enumerate()：同時要編號和內容
print("😩 笨方法")
for i in range(len(今日訂單)):
    print(i, 今日訂單[i])

print("\n🙂 Python 的方法")
for 序號, 金額 in enumerate(今日訂單, start=1):
    print(f"第 {序號} 筆：{金額} 元")

