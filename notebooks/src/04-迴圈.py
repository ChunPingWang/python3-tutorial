# ## 4.6 break / continue / for-else

# %%
for 金額 in 今日訂單:
    if 金額 > 100:
        print("找到大額訂單", 金額)
        break              # 立刻跳出整個迴圈

# %%
含退款 = [65, 0, 45, 0, 120]
有效總額 = 0
for 金額 in 含退款:
    if 金額 == 0:
        continue           # 跳過這一圈，直接進下一圈
    有效總額 += 金額
print("有效總額：", 有效總額)

# %%
# Python 獨有的 for-else：迴圈「沒有被 break」才執行 else
for 金額 in 今日訂單:
    if 金額 > 1000:
        print("有超大訂單")
        break
else:
    print("今天沒有超大訂單")       # 沒 break 過才執行

# %% [markdown]
# > 🔍 這個 `else` 語意很違反直覺（很多人認為它命名錯誤），用途是「搜尋失敗時做什麼」。
