# ## 4.8 🟢 讓測試變綠

# %%
from decimal import Decimal, ROUND_HALF_UP


def 四捨五入(數值) -> int:
    return int(Decimal(str(數值)).quantize(Decimal("1"), rounding=ROUND_HALF_UP))


def 總營收(訂單):
    總額 = 0
    for 金額 in 訂單:
        總額 += 金額
    return 總額


def 最貴一筆(訂單):
    最大 = 訂單[0]
    for 金額 in 訂單:
        if 金額 > 最大:
            最大 = 金額
    return 最大


def 筆數(訂單):
    數 = 0
    for _ in 訂單:           # _ 代表「這個值我不用」
        數 += 1
    return 數


def 平均客單價(訂單):
    return 四捨五入(總營收(訂單) / 筆數(訂單))

# %%
assert 總營收(今日訂單) == 440
assert 最貴一筆(今日訂單) == 120
assert 筆數(今日訂單) == 6
assert 平均客單價(今日訂單) == 73
print("🟢 全綠")

