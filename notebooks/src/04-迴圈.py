# # 第 4 章：迴圈 —— 把重複的事交給電腦
#
# > 🎬 **情境**
# > 打烊了。阿宏把訂單本丟給你：「一共 187 筆。算今天賣多少、哪一筆最貴、有幾筆是會員。
# > 喔對，明天開始每天都要。」
#
# 你昨天處理一筆要寫 3 行，今天要寫 561 行，明天再 561 行。

# %% [markdown]
# ## 4.1 😩 土法煉鋼：複製貼上

# %%
總額 = 0
總額 = 總額 + 65
總額 = 總額 + 45
總額 = 總額 + 65
總額 = 總額 + 55
# ...還有 183 行
print(總額, "（才做了 4 筆…）")

# %% [markdown]
# 問題不只是累：
#
# 1. **會漏、會重複**，而且自己看不出來
# 2. **明天的資料不一樣**，561 行要全部重寫
# 3. **阿宏改規則**（例如會員不計入），要改 187 個地方
#
# > **只要你在複製貼上程式碼，就代表你需要迴圈。**

# %% [markdown]
# ## 4.2 🧪 先寫測試

# %%
今日訂單 = [65, 45, 65, 55, 120, 90]      # 先用 6 筆代表 187 筆

try:
    assert 總營收(今日訂單) == 440
    assert 最貴一筆(今日訂單) == 120
except NameError as 錯誤:
    print("🔴 紅燈：", 錯誤)

# %% [markdown]
# > 🔍 **為什麼測試只用 6 筆，不用 187 筆？**
# > 因為測試要**跑得快、看得懂、壞了能馬上定位**。6 筆你可以心算驗證，187 筆你不行。
# > **好的測試資料是「最小但涵蓋所有情況」的資料**，不是真實資料的複製品。
# > 187 筆是拿來驗收的，6 筆是拿來開發的。

# %% [markdown]
# ## 4.3 💡 for：對每一個東西做一次

# %%
for 金額 in 今日訂單:
    print(金額)

# %% [markdown]
# 讀法：**「對於 `今日訂單` 裡的每一個東西，把它叫做 `金額`，然後做底下的事。」**

# %%
總額 = 0
for 金額 in 今日訂單:
    總額 += 金額           # 等同 總額 = 總額 + 金額
print(總額)

# %% [markdown]
# 6 筆是這 3 行，187 筆也是這 3 行，10000 筆還是這 3 行。**這就是迴圈的意義。**

# %% [markdown]
# ### 累加器模式：三步驟
#
# ```
# 總額 = 0          ← 1. 迴圈「外面」準備起始值
# for x in 清單:
#     總額 += x     ← 2. 迴圈「裡面」更新
# print(總額)       ← 3. 迴圈「外面」使用結果
# ```

# %%
# ⚠️ 最常見的錯誤 1：把起始值放進迴圈裡
總額 = 0
for 金額 in 今日訂單:
    總額 = 0          # ✖ 每一圈都歸零
    總額 += 金額
print("錯誤版本：", 總額, "← 只剩最後一筆！")

# %%
# ⚠️ 最常見的錯誤 2：print 放錯層（縮排差一格，意義完全不同）
總額 = 0
print("--- print 在迴圈裡（印 6 次）---")
for 金額 in 今日訂單:
    總額 += 金額
    print(總額)

總額 = 0
for 金額 in 今日訂單:
    總額 += 金額
print("--- print 在迴圈外（印 1 次，通常你要的是這個）---")
print(總額)

# %% [markdown]
# ### 找最大值

# %%
最大 = 今日訂單[0]          # 先假設第一筆最大
for 金額 in 今日訂單:
    if 金額 > 最大:
        最大 = 金額
print("最貴：", 最大)

# %% [markdown]
# ⚠️ 起始值不要寫 `最大 = 0`。萬一資料全是負數（例如退款紀錄）就錯了。
# **用第一筆當起點才安全。**

# %%
# 親眼看 最大 = 0 的錯誤
退款紀錄 = [-30, -65, -45]

錯的最大 = 0
for x in 退款紀錄:
    if x > 錯的最大:
        錯的最大 = x

對的最大 = 退款紀錄[0]
for x in 退款紀錄:
    if x > 對的最大:
        對的最大 = x

print("從 0 開始：", 錯的最大, "← 這筆資料根本不存在！")
print("從第一筆開始：", 對的最大, "✔")

# %% [markdown]
# > 🔍 Python 內建 `sum()`、`max()`、`len()` 直接就能做。
# > **那為什麼還要手寫迴圈？** 因為內建函式只處理最單純的情況。
# > 當阿宏說「只算會員的、而且排除退款」時，你還是得自己寫。**先懂原理，再用捷徑。**

# %%
print(sum(今日訂單), max(今日訂單), min(今日訂單), len(今日訂單))

