# %% [markdown]
# ## 4.5 while：條件成立就一直做
#
# `for` 是「已知要做幾次」，`while` 是「做到某個條件為止」。

# %%
庫存 = 10
賣出 = 0
while 庫存 > 0:
    庫存 -= 1
    賣出 += 1
print(f"賣完了，共賣出 {賣出} 杯")

# %% [markdown]
# ### ⚠️ 無窮迴圈
#
# ```python
# 庫存 = 10
# while 庫存 > 0:
#     print("賣一杯")     # 忘了減庫存 → 永遠停不下來
# ```
#
# **Jupyter 按 `I` 兩下（或工具列 ■）中斷；終端機按 `Ctrl + C`。**
#
# 寫 `while` 養成習慣問兩個問題：
#
# 1. 迴圈裡**哪一行**會讓條件逐漸變成假？
# 2. 有沒有可能永遠變不成假？

# %%
# 加保險絲：怕寫錯就設一個上限
次數 = 0
庫存 = 10
while 庫存 > 0:
    庫存 -= 1
    次數 += 1
    if 次數 > 1000:                # 保險絲
        raise RuntimeError("迴圈跑太多次，可能寫錯了")
print("🟢 安全結束，跑了", 次數, "圈")

