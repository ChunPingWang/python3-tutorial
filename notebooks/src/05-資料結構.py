# %% [markdown]
# > 🔍 **字典為什麼快？**
# > 字典用雜湊表（hash table）實作，查一筆的時間**和資料量無關** —— 1 萬筆和 10 筆一樣快。
# > 用清單搜尋要一筆一筆比對，1 萬筆就慢 1000 倍。
# >
# > **第 4 章說的「巢狀迴圈太慢」，解法通常就是先建一個字典。**

# %%
# 親眼比較一下（不用看懂 timeit，看數字就好）
import timeit

大清單 = list(range(100_000))
大集合 = set(大清單)

清單時間 = timeit.timeit(lambda: 99_999 in 大清單, number=100)
集合時間 = timeit.timeit(lambda: 99_999 in 大集合, number=100)
print(f"在 10 萬筆裡找東西，做 100 次：")
print(f"  清單：{清單時間:.4f} 秒")
print(f"  集合：{集合時間:.6f} 秒  ← 快了幾千倍")

