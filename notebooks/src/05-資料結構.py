# ## 5.8 🟢 讓測試變綠 + 統計熱銷

# %%
from collections import Counter


def 品項數量(菜單):
    return len(菜單)


def 賣出品項(訂單):
    return set(訂單)


def 熱銷品項(訂單):
    return Counter(訂單).most_common(1)[0][0]


今日訂單 = ["珍珠奶茶", "冬瓜檸檬", "珍珠奶茶", "紅茶"]

assert 查價("珍珠奶茶", "大杯") == 65
assert 查價("珍珠奶茶", "中杯") == 55
assert 品項數量(菜單) == 3
assert 賣出品項(今日訂單) == {"珍珠奶茶", "冬瓜檸檬", "紅茶"}
assert 熱銷品項(今日訂單) == "珍珠奶茶"
print("🟢 全綠")

# %%
# Counter 是標準庫送你的計數器（第 12 章詳談）
print(Counter(今日訂單))
print(Counter(今日訂單).most_common(2))

# 手寫版本（理解原理用）：.get 預設值的經典用法
次數 = {}
for 品項 in 今日訂單:
    次數[品項] = 次數.get(品項, 0) + 1
print(次數)
assert 次數 == dict(Counter(今日訂單))
print("🟢 手寫版和 Counter 結果相同")

