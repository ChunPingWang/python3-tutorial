# ## 5.2 Python 的四種基本容器
#
# | 容器 | 長相 | 有順序 | 可修改 | 有重複 | 什麼時候用 |
# | --- | --- | --- | --- | --- | --- |
# | **list** 串列 | `[65, 45, 120]` | ✔ | ✔ | ✔ | 一串同類型的東西 |
# | **tuple** 元組 | `(25.03, 121.5)` | ✔ | ✖ | ✔ | 一組固定不變的值 |
# | **dict** 字典 | `{"珍奶": 65}` | ✔ | ✔ | 鍵不重複 | **查表** |
# | **set** 集合 | `{"珍奶", "紅茶"}` | ✖ | ✔ | ✖ | **去重複**、判斷有沒有 |
