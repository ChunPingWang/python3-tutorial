# %% [markdown]
# ### 串列推導式（list comprehension）

# %%
訂單 = [65, 45, 120]

# 😩 一般寫法
含稅清單 = []
for 金額 in 訂單:
    含稅清單.append(round(金額 * 1.05))

# 🙂 推導式：一行搞定
含稅推導 = [round(金額 * 1.05) for 金額 in 訂單]

print(含稅清單)
