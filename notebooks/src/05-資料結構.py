# ## 5.5 💡 dict：查表 —— 阿宏問題的答案

# %%
單價表 = {
    "珍珠奶茶": 65,
    "冬瓜檸檬": 45,
    "紅茶": 35,
}

print(單價表["珍珠奶茶"])       # 查表
單價表["椰果奶茶"] = 60         # 新增
單價表["紅茶"] = 38            # 鍵已存在 → 修改
print(單價表)
print("珍珠奶茶" in 單價表, len(單價表))

# %%
# ⚠️ 查不到的鍵會爆炸
try:
    單價表["綠茶"]
except KeyError as 錯誤:
    print("🔴 KeyError：", 錯誤)

# 三種安全查法
print(單價表.get("綠茶"))         # None
print(單價表.get("綠茶", 0))      # 指定預設值 ← 最常用
print("綠茶" in 單價表)

# %% [markdown]
# > 🔍 **什麼時候用 `[]`，什麼時候用 `.get()`？**
# >
# > - 用 `[]`：這個鍵**一定要存在**，不存在就是 bug，我要它立刻爆給我看。
# > - 用 `.get()`：這個鍵**可能不存在**，那是正常情況，給預設值就好。
# >
# > 別無腦一律用 `.get()` —— 那會把真正的 bug 藏起來，變成後面某處莫名其妙的 `None`。

# %%
# 走訪字典
for 品名, 價格 in 單價表.items():          # 最常用
    print(f"{品名:<8}{價格:>4}")

print("\n所有鍵：", list(單價表.keys()))
print("所有值：", list(單價表.values()))
print("總和  ：", sum(單價表.values()))

