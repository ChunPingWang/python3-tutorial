# ## 5.7 💡 tuple：不可修改的一組值

# %%
一筆訂單 = ("珍珠奶茶", "大杯", 65)
品名, 杯型, 價格 = 一筆訂單          # 拆包 unpacking
print(品名, 杯型, 價格)

try:
    一筆訂單[0] = "紅茶"
except TypeError as 錯誤:
    print("🔴 TypeError：", 錯誤, "← tuple 不能改")

# %% [markdown]
# tuple 和 list 幾乎一樣，差別只有不能修改。那為什麼要用它？
#
# 1. **表達「這組值不該被改」** —— 座標、一筆紀錄
# 2. **可以當字典的鍵**（list 不行，會變的東西不能當鍵）
# 3. **函式回傳多個值時，Python 自動用 tuple**

# %%
def 統計(訂單):
    return sum(訂單), max(訂單), len(訂單)      # 其實回傳一個 tuple


結果 = 統計([65, 45, 120])
print("原樣：", 結果, type(結果).__name__)

總額, 最大, 筆數 = 統計([65, 45, 120])           # 自動拆包
print(f"{總額=} {最大=} {筆數=}")

# %%
# tuple 當字典的鍵：記錄每個 (品項, 杯型) 組合賣了幾杯
銷量 = {
    ("珍珠奶茶", "大杯"): 32,
    ("珍珠奶茶", "中杯"): 18,
}
print(銷量[("珍珠奶茶", "大杯")])

# list 不能當鍵
try:
    {["珍珠奶茶", "大杯"]: 32}
except TypeError as 錯誤:
    print("🔴 TypeError：", 錯誤)

