# > 🎬 **情境**
# > 阿宏遞給你一張紙條：「今天第一杯，珍珠奶茶，大杯，65 元，付現。你先幫我記到電腦裡。」
#
# 本章目標：讓電腦**記住**一件事，並且學會用 `assert` 把「我期待什麼」寫下來。

# %% [markdown]
# ## 1.1 😩 土法煉鋼：只會 print 的世界

# %%
print("珍珠奶茶")
print("大杯")
print(65)
print("付現")

# %% [markdown]
# 印出來了，看起來很成功。但阿宏接著問：**「那賣 3 杯是多少錢？」**
#
# 你做不到。因為 `print` 只是「把東西顯示在螢幕上」，說完就忘 —— 電腦並沒有**記住**那個 65。
#
# > 🔍 `print` 不是「執行」，而是「給人看」。程式內部的運算完全不需要 `print` 也能進行。

# %% [markdown]
# ## 1.2 🧪 先寫測試：把期待寫下來
#
# 寫程式之前先問自己：**「做完之後，什麼事情會是真的？」**
#
# 下面這格會 **🔴 紅燈**，這是刻意的。

# %%
try:
    assert 品項 == "珍珠奶茶"
    assert 單價 == 65
except NameError as 錯誤:
    print("🔴 紅燈：", 錯誤)
    print("   意思是：你用了一個還不存在的名字。")

# %% [markdown]
# 🔴 紅燈不是失敗，紅燈是「需求已經講清楚了，而且電腦確認我還沒做到」。
#
# > 🔍 **為什麼一定要先看到紅燈？**
# > 因為一個從來沒紅過的測試，你不知道它到底有沒有在檢查東西。
# > 萬一測試裡有 typo，它可能什麼都沒測就綠燈了。**先紅，才證明這個測試是活的。**

# %% [markdown]
# ## 1.3 💡 解法：變數
#
# 變數就是「幫一個值取名字，讓它留在記憶體裡」。

# %%
品項 = "珍珠奶茶"
杯型 = "大杯"
單價 = 65
付款方式 = "現金"

# %% [markdown]
# 現在再跑一次測試 —— 而且順便回答阿宏「3 杯多少錢」的問題。

# %%
assert 品項 == "珍珠奶茶"
assert 杯型 == "大杯"
assert 單價 == 65
assert 單價 * 3 == 195          # ← 阿宏問的問題
print("🟢 全部通過，三杯是", 單價 * 3, "元")

# %% [markdown]
# ## 1.4 `=` 不是「等於」，是「取名字」
#
# 這是初學者第一個大坑。

# %%
單價 = 65        # 賦值：把 65 這個值，取名叫「單價」
print(單價 == 65)  # 比較：單價是不是等於 65？→ 回答 True 或 False
print(單價 == 70)

# %% [markdown]
# | 符號 | 名稱 | 做什麼 | 回傳 |
# | --- | --- | --- | --- |
# | `=` | 賦值 | 把右邊的值綁到左邊的名字上 | 不回傳東西 |
# | `==` | 比較 | 問左右兩邊是否相等 | `True` / `False` |
#
# `assert` 後面幾乎一定是 `==`，因為你在**問問題**，不是在命名。

# %% [markdown]
# ## 1.5 變數是名牌，不是箱子

# %%
單價 = 65
單價 = 70          # 阿宏漲價了
assert 單價 == 70
print("現在的單價是", 單價)

# %% [markdown]
# 你不是把箱子裡的 65 換成 70，而是把「單價」這張名牌從 65 撕下來，貼到 70 上面。

# %% [markdown]
# ## 1.6 型別：值的種類
#
# 阿宏說「把價格跟品項黏起來給我看」，你天真地試了 `品項 + 單價`：

# %%
try:
    print(品項 + 單價)
except TypeError as 錯誤:
    print("🔴 TypeError：", 錯誤)
    print("   翻譯：字串只能跟字串相加，你卻給了一個整數。")

# %% [markdown]
# 因為 Python 裡每個值都有**型別**：

# %%
print(type("珍珠奶茶"))   # str   字串
print(type(65))          # int   整數
print(type(65.5))        # float 浮點數
print(type(True))        # bool  布林
print(type(None))        # NoneType 空值

# %% [markdown]
# | 型別 | 例子 | 什麼時候用 |
# | --- | --- | --- |
# | `str` | `"珍珠奶茶"` | 任何文字。**電話號碼、訂單編號也要用 str！** |
# | `int` | `65` | 杯數、價格 |
# | `float` | `0.9` | 折扣率、平均值 |
# | `bool` | `True` | 是不是會員、有沒有加珍珠 |
# | `None` | `None` | 還沒填、查不到、沒有結果 |
#
# > 🔍 **為什麼電話號碼要用字串？**
# > 因為 `0912345678` 存成整數，開頭的 0 會不見。
# > **判斷準則：這個值會不會拿來做數學運算？不會的話就用字串。**

# %%
# 親眼看看 0 消失
print("存成整數：", 912345678)      # 你永遠打不出開頭的 0
print("存成字串：", "0912345678")   # 完整保留

# %% [markdown]
# ## 1.7 型別轉換

# %%
print(str(65),   type(str(65)))
print(int("65"), type(int("65")))
print(float("65"), type(float("65")))
print(int(65.9))   # ⚠️ 直接砍掉小數，不是四捨五入！

# %%
# 所以「把品項跟價格黏起來」要這樣寫（醜版本，第 2 章有優雅一百倍的寫法）
print(品項 + " " + str(單價) + " 元")

# %%
# ⚠️ 型別轉換不是萬能翻譯
try:
    int("六十五")
except ValueError as 錯誤:
    print("🔴 ValueError：", 錯誤)
    print("   意思是：這個字串的內容沒辦法當成數字看待。")

# %% [markdown]
# ## 1.8 變數命名

# %%
# 😩 三個月後的你會恨死現在的你
a = "珍珠奶茶"
b = 65
c = 3
d = b * c

# 🙂 好多了
品項名稱 = "珍珠奶茶"
單價 = 65
數量 = 3
小計 = 單價 * 數量

assert d == 小計      # 電腦來說完全一樣，差別只在人看不看得懂
print("🟢 兩種寫法結果相同，但只有一種你半年後看得懂")

# %% [markdown]
# **語法強制的規則**
#
# - 不能用數字開頭：`2杯 = 5` ❌
# - 不能用保留字：`class`、`if`、`for`、`return`、`import`…
# - 區分大小寫
#
# **慣例（不強制，但全世界都這樣做）**
#
# | 種類 | 寫法 | 例子 |
# | --- | --- | --- |
# | 變數、函式 | snake_case | `total_price`、`is_member` |
# | 常數 | 全大寫 | `TAX_RATE = 0.05` |
# | 類別 | PascalCase | `Order` |
#
# > 🔍 教材前幾章用中文變數名，是為了讓你專心在**概念**而不是英文單字。
# > 正式專案請用英文，第 6 章起教材會帶你自然過渡。

